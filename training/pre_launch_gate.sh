#!/usr/bin/env bash
# 4.1 の起動前関門。**手順書はこれを呼ぶだけ**。
#
# 34 巡目の測定: 4.1 は静的にも動的にも検査されていなかった——
#   - doc_check は「pre_launch_check.py という文字列が本文にあるか」しか見ず、
#     コメントに残っていれば呼び出し行を消しても通った
#   - gate_run は 4.1 ブロックを mkdir/リダイレクト/$TAG で除外していた
#   - export DIM/NLAYER を関門の後ろへ移すと、関門が常に「未設定」で落ちるので
#     作業者は関門を無視することを学習する
# ∴ env 設定と関門呼び出しだけを 1 本に切り出し、gate_run が実行できる形にする。
set -euo pipefail
cd "$(dirname "$0")"

# ⚠ **既定を与えない。** 36 巡目: `${DIM:-256}` としていたため、
#    関門が「自分が入れた既定」を照合するだけの空検査になっていた。
#    しかも子プロセスなので親に伝播せず、4.1 の arch.txt が `DIM= NLAYER=` で焼かれ、
#    4.2 のガードが起動を拒否し、4.6 の resume も不能になっていた。
: "${DIM:?DIM が未設定。4.1 の先頭で 2.4b の実測構成を export する}"
: "${NLAYER:?NLAYER が未設定。4.1 の先頭で export する}"

uv run python pre_launch_check.py
